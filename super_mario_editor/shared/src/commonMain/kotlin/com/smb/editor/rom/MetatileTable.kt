package com.smb.editor.rom

/**
 * A 16x16 metatile composed of 4 8x8 CHR tiles.
 * CHR tile indices refer to the background tile bank (tiles 0-255).
 */
data class Metatile(
    val topLeft: Int,     // CHR tile index
    val topRight: Int,
    val bottomLeft: Int,
    val bottomRight: Int,
    val paletteIndex: Int // which of the 4 sub-palettes (0-3)
)

object MetatileTable {
    /**
     * Canonical SMB metatile definitions derived from `smbdis.asm`
     * (`Palette0_MTiles`..`Palette3_MTiles`), mapped to renderer-local IDs.
     */
    fun getMetatiles(): List<Metatile> {
        return listOf(
            // 0x00-0x0A: core gameplay tiles
            Metatile(0x24, 0x24, 0x24, 0x24, 0), // 0x00 blank / sky
            Metatile(0xB4, 0xB6, 0xB5, 0xB7, 1), // 0x01 ground (cracked rock)
            Metatile(0x27, 0x27, 0x27, 0x27, 0), // 0x02 black fill
            Metatile(0x45, 0x47, 0x45, 0x47, 1), // 0x03 brick
            Metatile(0x53, 0x55, 0x54, 0x56, 3), // 0x04 question block
            Metatile(0x57, 0x59, 0x58, 0x5A, 3), // 0x05 used/empty block
            Metatile(0x60, 0x64, 0x61, 0x65, 0), // 0x06 pipe top-left
            Metatile(0x62, 0x66, 0x63, 0x67, 0), // 0x07 pipe top-right
            Metatile(0x68, 0x68, 0x69, 0x69, 0), // 0x08 pipe shaft-left
            Metatile(0x26, 0x26, 0x6A, 0x6A, 0), // 0x09 pipe shaft-right
            Metatile(0xA5, 0xA7, 0xA6, 0xA8, 3), // 0x0A coin

            // 0x0B-0x13: clouds/castle/flagpole
            Metatile(0x24, 0x24, 0x24, 0x35, 2), // 0x0B cloud left
            Metatile(0x24, 0x38, 0x24, 0x24, 2), // 0x0C cloud right
            Metatile(0x24, 0x24, 0x39, 0x24, 2), // 0x0D cloud bottom-left
            Metatile(0x3C, 0x24, 0x24, 0x24, 2), // 0x0E cloud bottom-right
            Metatile(0x9D, 0x47, 0x9E, 0x47, 1), // 0x0F castle top
            Metatile(0x47, 0x47, 0x47, 0x47, 1), // 0x10 castle wall
            Metatile(0x47, 0x47, 0x27, 0x27, 1), // 0x11 castle window
            Metatile(0x24, 0x2F, 0x24, 0x3D, 0), // 0x12 flagpole ball
            Metatile(0xA2, 0xA2, 0xA3, 0xA3, 0), // 0x13 flagpole shaft

            // 0x14-0x1F: platforms/specials
            Metatile(0x6B, 0x70, 0x2C, 0x2D, 0), // 0x14 mushroom left edge
            Metatile(0x6C, 0x71, 0x6D, 0x72, 0), // 0x15 mushroom middle
            Metatile(0x6E, 0x73, 0x6F, 0x74, 0), // 0x16 mushroom right edge
            Metatile(0xBE, 0xBE, 0xBF, 0xBF, 1), // 0x17 tree trunk
            Metatile(0x41, 0x26, 0x41, 0x26, 2), // 0x18 water/lava top
            Metatile(0x26, 0x26, 0x26, 0x26, 2), // 0x19 water/lava body
            Metatile(0xA4, 0xE9, 0xEA, 0xEB, 0), // 0x1A seaplant
            Metatile(0xAB, 0xAC, 0xAD, 0xAE, 1), // 0x1B solid block (stairs)
            Metatile(0xC1, 0x24, 0xC1, 0x24, 1), // 0x1C bridge
            Metatile(0xCA, 0xCC, 0xCB, 0xCD, 1), // 0x1D cannon top
            Metatile(0x2A, 0x2A, 0x40, 0x40, 1), // 0x1E cannon bottom
            Metatile(0x77, 0x79, 0x77, 0x79, 2), // 0x1F bowser bridge

            // 0x20-0x26: scenery aliases used by LevelDecoder
            Metatile(0x26, 0x26, 0x26, 0x26, 0), // 0x20 hill body
            Metatile(0x24, 0x31, 0x24, 0x32, 0), // 0x21 hill top
            Metatile(0x36, 0x25, 0x37, 0x25, 2), // 0x22 cloud middle
            Metatile(0x3A, 0x24, 0x3B, 0x24, 2), // 0x23 cloud bottom-middle
            Metatile(0x24, 0x24, 0x24, 0x35, 0), // 0x24 bush left
            Metatile(0x36, 0x25, 0x37, 0x25, 0), // 0x25 bush middle
            Metatile(0x24, 0x38, 0x24, 0x24, 0), // 0x26 bush right

            // 0x27-0x2B: additional mountain pieces
            Metatile(0x24, 0x30, 0x30, 0x26, 0), // 0x27 mountain left
            Metatile(0x26, 0x26, 0x34, 0x26, 0), // 0x28 mountain left-bottom
            Metatile(0x33, 0x26, 0x24, 0x33, 0), // 0x29 mountain right
            Metatile(0x34, 0x26, 0x26, 0x26, 0), // 0x2A mountain right-bottom
            Metatile(0x26, 0x26, 0x26, 0x26, 0), // 0x2B mountain middle-bottom
            Metatile(0x80, 0xA0, 0x81, 0xA1, 1), // 0x2C fence
            Metatile(0xB8, 0xBA, 0xB9, 0xBB, 0), // 0x2D tall tree top (upper)
            Metatile(0xBA, 0xBC, 0xBB, 0xBD, 0), // 0x2E tall tree top (lower)
            Metatile(0xB8, 0xBC, 0xB9, 0xBD, 0), // 0x2F short tree top
        )
    }
}
