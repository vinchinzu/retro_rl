#!/usr/bin/env python3
"""Scaffold one pure-first continuous tip extension (recipe steps 1–5 checklist).

Does **not** claim continuous green or edit STATUS. Generates:

1. Pure controller stub in ``routes/kpdr/<module>.py`` (optional append)
2. Registry registration snippet / optional write
3. Residual skeleton under ``docs/tasks/``
4. Printed checklist for graph edge, catalog tip, SpineHop/TipSpec, run_to wire

Usage (from repo root)::

  uv run python snes/super_metroid/scripts/scaffold_tip.py \\
    --segment business_to_frog_save \\
    --from-room 0xA7DE --to-room 0xB167 \\
    --module k4_norfair --card-id SM-K4-BUBBLE-01 --dry-run

  uv run python snes/super_metroid/scripts/scaffold_tip.py \\
    --segment my_hop --from-room 0xA7DE --to-room 0xB167 \\
    --module k4_norfair --card-id SM-K4-XX --write
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
_SNES_IMPORT_ROOT = Path(__file__).resolve().parents[2]
for _p in (ROOT, globals().get('_SNES_IMPORT_ROOT', ROOT)):
    if _p is not None and str(_p) not in sys.path:
        sys.path.insert(0, str(_p))
SM = ROOT / "snes" / "super_metroid"
KPDR = SM / "routes" / "kpdr"
TASKS = SM / "docs" / "tasks"
REGISTRY = KPDR / "registry.py"


def _snake(s: str) -> str:
    s = s.strip().replace("-", "_")
    s = re.sub(r"[^a-zA-Z0-9_]+", "_", s)
    return s.lower().strip("_")


def _fn_name(segment: str) -> str:
    return f"play_{_snake(segment)}"


def _controller_stub(
    *,
    segment: str,
    from_room: int,
    to_room: int,
    module: str,
) -> str:
    fn = _fn_name(segment)
    label = _snake(segment)
    return f'''

def {fn}(session: ControllerSession) -> SuperMetroidState:
    """Scaffold {_snake(segment)}: 0x{from_room:04X} → 0x{to_room:04X}.

    Pure-first: green from continuous-like source before continuous tip wire.
    Generated by scripts/scaffold_tip.py — replace geometry before claiming green.
    """
    require_room(session, 0x{from_room:04X}, "{label}")
    # TODO: replace scaffold with real geometry (one knob at a time).
    for _ in range(240):
        state = hold(session, 1, reason="{label}_scaffold")
        if state.room_id == 0x{to_room:04X}:
            return state
    state = session.state
    raise TimeoutError(
        f"{label}: scaffold timeout before room 0x{to_room:04X}; "
        f"room=0x{{state.room_id:04X}} pose={{state.pose}} "
        f"xy=({{state.samus_x}},{{state.samus_y}})"
    )
'''


def _ensure_module_header(path: Path) -> str:
    if path.is_file():
        return path.read_text(encoding="utf-8")
    return f'''"""KPDR controllers for tip extension (scaffold).

Generated / extended via ``scripts/scaffold_tip.py``.
"""

from __future__ import annotations

from super_metroid.ram import SuperMetroidState
from super_metroid.routes.controller_common import hold, require_room
from super_metroid.routes.runtime import ControllerSession
'''


