def _checklist(
    *,
    segment: str,
    from_room: int,
    to_room: int,
    module: str,
    card_id: str,
) -> str:
    fn = _fn_name(segment)
    edge_id = _snake(segment)
    return f"""
## Tip-extension checklist (planner / follow-up cards)

| Step | Action | Owner |
|------|--------|-------|
| 1 | Pure controller `{fn}` in `routes/kpdr/{module}.py` + `KPDR_SEGMENTS` | Luna (this scaffold) |
| 2 | `DoorEdge` `{edge_id}` in `progression.py` (`verification=controller_dev` after pure green) | Luna / planner |
| 3 | Split id + optional `ContinuousTip` in `catalog.py` | Luna (after pure) |
| 4 | `SpineHop` + `TipSegment` in spine; TipSpec generates | Luna (after pure) |
| 5 | `run_to()` + `register_continuous_segments` | Luna (after pure) |
| 6 | `scripts/record/continuous.py --to <tip> --no-video` | **Planner** |
| 7 | STATUS / tracker promote | **Planner** only |

Rooms: 0x{from_room:04X} → 0x{to_room:04X}
Card: {card_id}

Graph pure-gate helper (from Python):
```python
from super_metroid.progression import SPEED_GRAPH, capabilities_from_state
# gate = SPEED_GRAPH.pure_gate(0x{from_room:04X}, 0x{to_room:04X}, caps)
# work = SPEED_GRAPH.suggest_pure_work(0x{from_room:04X}, capabilities=caps)
```
"""


def _register_snippet(segment: str, module: str) -> str:
    fn = _fn_name(segment)
    key = _snake(segment)
    return (
        f'from super_metroid.routes.kpdr.{module} import {fn}\n'
        f'# In KPDR_SEGMENTS:\n'
        f'    "{key}": {fn},\n'
    )


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--segment", required=True, help="Segment id (snake or kebab)")
    p.add_argument(
        "--from-room",
        type=lambda s: int(s, 0),
        required=True,
        help="Entry room id (0x… or int)",
    )
    p.add_argument(
        "--to-room",
        type=lambda s: int(s, 0),
        required=True,
        help="Exit room id (0x… or int)",
    )
    p.add_argument(
        "--module",
        default="k4_norfair",
        help="kpdr module stem (default k4_norfair)",
    )
    p.add_argument(
        "--card-id",
        default="",
        help="Task card id (default SM-SCAFFOLD-<SEGMENT>)",
    )
    p.add_argument(
        "--write",
        action="store_true",
        help="Write module stub + residual card (default dry-run print only)",
    )
    p.add_argument(
        "--dry-run",
        action="store_true",
        help="Force print-only even with --write",
    )
    p.add_argument(
        "--register",
        action="store_true",
        help="Also append KPDR_SEGMENTS entry when --write (careful)",
    )
    args = p.parse_args()

    segment = _snake(args.segment)
    card_id = args.card_id or f"SM-SCAFFOLD-{segment.upper().replace('_', '-')}"
    module_path = KPDR / f"{args.module}.py"
    residual_path = TASKS / f"{card_id}.md"
    write = args.write and not args.dry_run

    stub = _controller_stub(
        segment=segment,
        from_room=args.from_room,
        to_room=args.to_room,
        module=args.module,
    )
    residual = _residual_md(
        card_id=card_id,
        segment=segment,
        from_room=args.from_room,
        to_room=args.to_room,
        module=args.module,
    )
    checklist = _checklist(
        segment=segment,
        from_room=args.from_room,
        to_room=args.to_room,
        module=args.module,
        card_id=card_id,
    )
    reg = _register_snippet(segment, args.module)

    print("=== controller stub ===")
    print(stub)
    print("=== registry snippet ===")
    print(reg)
    print(checklist)

    if not write:
        print(f"[dry-run] would write {module_path}")
        print(f"[dry-run] would write {residual_path}")
        return

    text = _ensure_module_header(module_path)
    fn = _fn_name(segment)
    if f"def {fn}(" in text:
        print(f"skip controller: {fn} already in {module_path}")
    else:
        # Ensure imports exist for require_room/hold when appending to existing.
        if "require_room" not in text:
            text = text.rstrip() + (
                "\nfrom super_metroid.routes.controller_common import hold, require_room\n"
            )
        if "ControllerSession" not in text:
            text = text.rstrip() + (
                "\nfrom super_metroid.routes.runtime import ControllerSession\n"
            )
        if "SuperMetroidState" not in text:
            text = text.rstrip() + (
                "\nfrom super_metroid.ram import SuperMetroidState\n"
            )
        module_path.write_text(text.rstrip() + "\n" + stub, encoding="utf-8")
        print(f"wrote {module_path.relative_to(ROOT)}")

    if residual_path.is_file():
        print(f"skip residual: exists {residual_path}")
    else:
        residual_path.write_text(residual, encoding="utf-8")
        print(f"wrote {residual_path.relative_to(ROOT)}")

    if args.register:
        reg_text = REGISTRY.read_text(encoding="utf-8")
        key = segment
        if f'"{key}"' in reg_text:
            print(f"skip registry: {key} already registered")
        else:
            import_line = (
                f"from super_metroid.routes.kpdr.{args.module} import {fn}\n"
            )
            if import_line not in reg_text:
                # Insert import near other kpdr imports (before SegmentFn).
                marker = "SegmentFn = Callable"
                if marker in reg_text:
                    reg_text = reg_text.replace(marker, import_line + "\n" + marker)
                else:
                    reg_text = import_line + reg_text
            entry = f'    "{key}": {fn},\n'
            close = "\n}\n\n\ndef get_segment"
            if close in reg_text:
                reg_text = reg_text.replace(close, "\n" + entry + "}\n\n\ndef get_segment")
            else:
                print("warn: could not find KPDR_SEGMENTS close; print entry only")
                print(entry)
            REGISTRY.write_text(reg_text, encoding="utf-8")
            print(f"updated {REGISTRY.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
